TABLES_SQL = r"""
-- Образовательные программы (версии учебного плана)
CREATE TABLE educational_programs (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction_code CHAR(8)      NOT NULL
        CONSTRAINT educational_programs_code_ck
        CHECK (direction_code ~ '^[0-9]{2}\.0[345]\.[0-9]{2}$'),
    profile        VARCHAR(150) NOT NULL
        CONSTRAINT educational_programs_profile_ck CHECK (btrim(profile) <> ''),
    cohort_year    SMALLINT     NOT NULL
        CONSTRAINT educational_programs_year_ck CHECK (cohort_year >= 2016),
    study_form     VARCHAR(12)  NOT NULL
        CONSTRAINT educational_programs_form_ck
        CHECK (study_form IN ('очная', 'очно-заочная', 'заочная')),
    revision_no    SMALLINT     NOT NULL
        CONSTRAINT educational_programs_revision_ck CHECK (revision_no > 0),
    semester_count SMALLINT     NOT NULL
        CONSTRAINT educational_programs_semesters_ck CHECK (semester_count BETWEEN 1 AND 14),
    CONSTRAINT educational_programs_version_uq
        UNIQUE (direction_code, profile, cohort_year, study_form, revision_no)
);

-- Учебные группы
CREATE TABLE student_groups (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR(8) NOT NULL
        CONSTRAINT student_groups_name_uq UNIQUE
        CONSTRAINT student_groups_name_ck CHECK (group_name ~ '^[0-9]{3}-[0-9]{3,4}$'),
    program_id INTEGER    NOT NULL
        REFERENCES educational_programs (id) ON DELETE RESTRICT
);

-- Контингент студентов
CREATE TABLE students (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name      VARCHAR(60) NOT NULL
        CONSTRAINT students_last_name_ck CHECK (btrim(last_name) <> ''),
    first_name     VARCHAR(60) NOT NULL
        CONSTRAINT students_first_name_ck CHECK (btrim(first_name) <> ''),
    patronymic     VARCHAR(60),
    student_no     VARCHAR(10) NOT NULL
        CONSTRAINT students_no_uq UNIQUE
        CONSTRAINT students_no_ck CHECK (student_no ~ '^[0-9]{1,10}$'),
    admission_year SMALLINT    NOT NULL
        CONSTRAINT students_year_ck CHECK (admission_year >= 2016),
    group_id       INTEGER     NOT NULL
        REFERENCES student_groups (id) ON DELETE RESTRICT,
    status         VARCHAR(30) NOT NULL
        CONSTRAINT students_status_ck CHECK (status IN (
            'обучается', 'академический отпуск', 'отпуск по беременности и родам',
            'отпуск по уходу за ребёнком', 'отчислен', 'выпускник'))
);

-- Учебный план: компоненты программы по семестрам
CREATE TABLE study_plans (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id  INTEGER      NOT NULL
        REFERENCES educational_programs (id) ON DELETE RESTRICT,
    discipline  VARCHAR(150) NOT NULL
        CONSTRAINT study_plans_discipline_ck CHECK (btrim(discipline) <> ''),
    semester    SMALLINT     NOT NULL
        CONSTRAINT study_plans_semester_ck CHECK (semester >= 1),
    hours       SMALLINT     NOT NULL
        CONSTRAINT study_plans_hours_ck CHECK (hours > 0),
    report_form VARCHAR(15)  NOT NULL
        CONSTRAINT study_plans_form_ck
        CHECK (report_form IN ('экзамен', 'зачёт', 'зачёт с оценкой')),
    CONSTRAINT study_plans_component_uq UNIQUE (program_id, discipline, semester)
);

-- Журнал успеваемости: события аттестации
CREATE TABLE grades (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    INTEGER     NOT NULL REFERENCES students (id) ON DELETE RESTRICT,
    plan_id       INTEGER     NOT NULL REFERENCES study_plans (id) ON DELETE RESTRICT,
    attempt_no    SMALLINT    NOT NULL
        CONSTRAINT grades_attempt_ck CHECK (attempt_no IN (1, 2, 3)),
    assessed_on   DATE        NOT NULL,
    grade         VARCHAR(10) NOT NULL
        CONSTRAINT grades_grade_ck
        CHECK (grade IN ('2', '3', '4', '5', 'зачтено', 'не зачтено', 'не явился')),
    basis_ref     VARCHAR(64) NOT NULL
        CONSTRAINT grades_basis_ck CHECK (btrim(basis_ref) <> ''),
    record_status VARCHAR(12) NOT NULL
        CONSTRAINT grades_status_ck CHECK (record_status IN ('черновик', 'зафиксирован')),
    CONSTRAINT grades_event_uq UNIQUE (student_id, plan_id, attempt_no, assessed_on)
);

-- Один результат на попытку; неявка по уважительной причине не считается
CREATE UNIQUE INDEX grades_result_uq ON grades (student_id, plan_id, attempt_no)
    WHERE grade <> 'не явился';

-- Дополнительные индексы под частые запросы
CREATE INDEX students_group_status_idx ON students (group_id, status);
CREATE INDEX student_groups_program_idx ON student_groups (program_id);
CREATE INDEX educational_programs_form_idx ON educational_programs (study_form);
CREATE INDEX study_plans_discipline_idx ON study_plans (discipline);
CREATE INDEX grades_plan_idx ON grades (plan_id);
"""

TRIGGERS_SQL = r"""
-- Семестр строки плана не больше числа семестров программы
CREATE FUNCTION study_plans_check_semester() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    max_semester SMALLINT;
BEGIN
    SELECT semester_count INTO max_semester
    FROM educational_programs WHERE id = NEW.program_id;
    IF NEW.semester > max_semester THEN
        RAISE EXCEPTION USING MESSAGE =
            'Семестр ' || NEW.semester || ' выходит за пределы программы (семестров: '
            || max_semester || ')';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER study_plans_semester_trg
    BEFORE INSERT OR UPDATE ON study_plans
    FOR EACH ROW EXECUTE FUNCTION study_plans_check_semester();

-- Строку плана с зафиксированными результатами менять нельзя
CREATE FUNCTION study_plans_protect_fixed() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM grades
               WHERE plan_id = OLD.id AND record_status = 'зафиксирован') THEN
        RAISE EXCEPTION USING MESSAGE =
            'По этой строке плана есть зафиксированные результаты. '
            'Создайте новую версию программы (revision_no)';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER study_plans_protect_trg
    BEFORE UPDATE ON study_plans
    FOR EACH ROW EXECUTE FUNCTION study_plans_protect_fixed();

-- Программа: число семестров не меньше семестров плана,
-- программу с зафиксированными результатами менять нельзя
CREATE FUNCTION educational_programs_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM grades g JOIN study_plans p ON p.id = g.plan_id
               WHERE p.program_id = OLD.id AND g.record_status = 'зафиксирован') THEN
        RAISE EXCEPTION USING MESSAGE =
            'По программе есть зафиксированные результаты. '
            'Создайте новую версию программы (revision_no)';
    END IF;
    IF EXISTS (SELECT 1 FROM study_plans
               WHERE program_id = OLD.id AND semester > NEW.semester_count) THEN
        RAISE EXCEPTION USING MESSAGE =
            'В учебном плане программы есть дисциплины в семестрах после '
            || NEW.semester_count;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER educational_programs_guard_trg
    BEFORE UPDATE ON educational_programs
    FOR EACH ROW EXECUTE FUNCTION educational_programs_guard();

-- Журнал: зафиксированная запись неизменна; дисциплина из плана студента;
-- оценка соответствует форме аттестации
CREATE FUNCTION grades_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    plan_form       VARCHAR(15);
    plan_program    INTEGER;
    student_program INTEGER;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') AND OLD.record_status = 'зафиксирован' THEN
        RAISE EXCEPTION USING MESSAGE =
            'Запись зафиксирована (ведомость закрыта) и не может изменяться';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    SELECT report_form, program_id INTO plan_form, plan_program
    FROM study_plans WHERE id = NEW.plan_id;
    SELECT g.program_id INTO student_program
    FROM students s JOIN student_groups g ON g.id = s.group_id
    WHERE s.id = NEW.student_id;

    IF plan_program IS DISTINCT FROM student_program THEN
        RAISE EXCEPTION USING MESSAGE = 'Дисциплина не входит в учебный план студента';
    END IF;
    IF NEW.grade <> 'не явился'
       AND (plan_form = 'зачёт') <> (NEW.grade IN ('зачтено', 'не зачтено')) THEN
        RAISE EXCEPTION USING MESSAGE =
            'Оценка «' || NEW.grade || '» не подходит для формы «' || plan_form || '»';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER grades_guard_trg
    BEFORE INSERT OR UPDATE OR DELETE ON grades
    FOR EACH ROW EXECUTE FUNCTION grades_guard();
"""


def _run(sql):
    # SQL передаётся драйверу как есть, без разбора параметров
    op.get_bind().exec_driver_sql(sql)


def upgrade():
    _run(TABLES_SQL)
    _run(TRIGGERS_SQL)


def downgrade():
    _run("DROP TABLE IF EXISTS grades, study_plans, students, "
         "student_groups, educational_programs")
    _run("DROP FUNCTION IF EXISTS study_plans_check_semester(), study_plans_protect_fixed(), "
         "educational_programs_guard(), grades_guard()")
